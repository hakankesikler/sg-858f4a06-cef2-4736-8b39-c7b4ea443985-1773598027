-- GPSLine parsiyel termin takvimi ve tahmini teslim tarihi hesaplama altyapısı.
CREATE TABLE IF NOT EXISTS public.supplier_transit_schedules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_code text NOT NULL,
  origin_region text NOT NULL,
  destination_region text NOT NULL,
  destination_city text NOT NULL,
  destination_district text NOT NULL,
  transit_business_days smallint NOT NULL CHECK (transit_business_days BETWEEN 1 AND 30),
  delivery_weekdays smallint[] NOT NULL CHECK (cardinality(delivery_weekdays) > 0),
  note text,
  source_document text NOT NULL,
  source_effective_date date NOT NULL,
  source_revision_date date,
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT supplier_transit_schedules_weekdays_check
    CHECK (delivery_weekdays <@ ARRAY[1,2,3,4,5,6]::smallint[]),
  CONSTRAINT supplier_transit_schedules_route_unique
    UNIQUE (provider_code, origin_region, destination_region, destination_district, source_effective_date)
);

CREATE INDEX IF NOT EXISTS supplier_transit_schedules_lookup_idx
  ON public.supplier_transit_schedules(provider_code, origin_region, destination_region, destination_district)
  WHERE active;

ALTER TABLE public.supplier_transit_schedules ENABLE ROW LEVEL SECURITY;
